"""Experimental single-version package export and comparison; no compilation.

The production shader_split entry point is unchanged. This independent writer
mirrors its deterministic format, verified by tests against the original writer
and by complete real package/table comparisons before any build integration.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import struct
import sys

from tools.nxrom.resourcefs import ResourceFS
from tools.nxrom.shader_scan import iter_resource, load_decoder, program_records

TABLES=('shader_map.tsv','shader_facts.tsv','shader_pairs.tsv')


def collect(resources, paths, main, decoder, verify_build, *, scratch=None):
    """Production precedence: main first (last copy within main), files sorted
    (first copy within each file). Preserve all pairs before deduplicating keys.
    """
    _,records=program_records(main,resources,decoder,verify_build)
    keys={decoder.skey(c,k):(w,s,c,k) for w,s,c,k in records}
    pairs=decoder.var_pairs(records)
    for path in sorted(set(paths)):
        with resources.open(path,buffering=0) as stream:
            records=list(iter_resource(stream,'/'+path,decoder,scratch=scratch))
        pairs |= decoder.var_pairs(records)
        for key,value in decoder.uniq_keys(records).items():
            if key in keys:
                if not decoder.same_shader(keys[key][2:4],value[2:4]):
                    raise ValueError('conflicting payloads for Shader key '+key)
            else: keys[key]=value
    extra,_=decoder.separable_pairs(keys)
    return keys,pairs|extra


def write_package(keys, pairs, output, decoder):
    """Write only into an exclusively created directory; never replace a cache."""
    output=Path(output)
    output.mkdir()
    package=output/'pkg'; package.mkdir()
    rows,facts=[],{}
    indices=collections.Counter()
    for key in sorted(keys,key=lambda k:(decoder.group(keys[k][0]),keys[k][0],k)):
        where,stage,control,code=keys[key]
        name=f'{stage}_{decoder.group(where)}.bin'
        # Group names become filenames, so reject profile values that escape pkg.
        if Path(name).name!=name or '\\' in name:
            raise ValueError('unsafe Shader package group')
        record=bytearray(b'BTCDBTCD'+bytes(0x30))
        struct.pack_into('<II',record,0x28,len(control),len(code))
        record+=code+control
        if record.find(decoder.CTL_MAGIC)!=0x38+len(code) or record.count(b'BTCDBTCD')!=1:
            raise ValueError('ambiguous Shader record delimiters')
        rows.append((name,indices[name],decoder.STAGE_NAME[stage],key,where))
        indices[name]+=1
        with (package/name).open('ab') as stream: stream.write(record)
        if stage=='cs':
            local=list(struct.unpack_from('<III',control,0x748))
            if not all(local): raise ValueError('zero compute Shader thread group')
            shared=struct.unpack_from('<I',control,0x754)[0]
            facts[key]={'local':local,'shared':(shared+15)//16*16}
    kinds=' / '.join(name for name,hit in (
        ('BNSH / BAHS',any('#BNSH@' in r[4] or '#BAHS@' in r[4] for r in rows)),
        ('Unity Shader',any('#var' in r[4] and '#BNSH@' not in r[4] and '#MSHD#' not in r[4] and '#SDF#' not in r[4] for r in rows)),
        ('MSHD',any('#MSHD#' in r[4] for r in rows)),('GLSLC',any('#GLSLC@' in r[4] for r in rows)),
        ('RE Engine SDF',any('#SDF#' in r[4] for r in rows)),('MT Framework SPK',any('#MTSPK@' in r[4] for r in rows)),
        ('MonoGame MGFX',any('#MGFX@' in r[4] for r in rows)),('Unreal Engine shader code archives',any('#UE' in r[4] for r in rows))) if hit)
    with (output/TABLES[0]).open('w') as stream:
        stream.write(f'# kind: evidence  {decoder.NOTE} ({kinds} in RomFS + main) → control section + code area keys (dm/gfx/tools/shader_split.py)\n')
        stream.write('# column 5 records where each key first appears; this game has no PC version to pair with\n')
        stream.write('package\tindex\tstage\tdm_ctl_sha16\tsource\n')
        for row in rows: stream.write('\t'.join(map(str,row))+'\n')
    manual=decoder.GAME.table('shader_facts_manual.tsv')
    if manual.exists():
        for line in manual.read_text().splitlines():
            if line.strip() and not line.startswith('#'):
                key,value=line.split('\t',1)
                facts[key]={**facts.get(key,{}),**json.loads(value)}
    with (output/TABLES[1]).open('w') as stream:
        stream.write('# Answer table for translation queries (generated by dm/gfx/tools/shader_split.py, do not edit): key <TAB> fact JSON. This game has no PC version to pair with: only the thread group / shared memory of compute shaders (taken from the control section); other queries get the translator defaults\n')
        for key in sorted(facts): stream.write(key+'\t'+json.dumps(facts[key],sort_keys=True,separators=(',',':'))+'\n')
    with (output/TABLES[2]).open('w') as stream:
        stream.write('# kind: evidence  vertex / pixel shader pairs within BNSH variations (generated by dm/gfx/tools/shader_split.py, do not edit): vertex key <TAB> pixel key\n')
        for vertex,pixel in sorted(pairs): stream.write(vertex+'\t'+pixel+'\n')


def digest(path):
    result=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda:stream.read(1024*1024),b''): result.update(block)
    return result.hexdigest()


def compare(output, reference, decoder):
    output,reference=Path(output),Path(reference)
    actual={p.name:digest(p) for p in (output/'pkg').glob('*.bin')}
    expected={p.name:digest(p) for p in reference.glob('*.bin')}
    tables={name:(output/name).read_bytes()==decoder.GAME.table(name).read_bytes() for name in TABLES}
    return {'packages':len(actual),'package_bytes':sum(p.stat().st_size for p in (output/'pkg').glob('*.bin')),
            'package_sha256':actual,'packages_equal':bool(expected) and actual==expected,
            'tables_byte_identical':tables,'translation_run':False}


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--library',type=Path,required=True)
    source=p.add_mutually_exclusive_group(required=True)
    source.add_argument('--base',type=Path); source.add_argument('--directory',type=Path)
    p.add_argument('--update',type=Path); p.add_argument('--keys',type=Path)
    p.add_argument('--title',type=lambda v:int(v,16),default=0)
    p.add_argument('--main',type=Path,required=True)
    selection=p.add_mutually_exclusive_group(required=True)
    selection.add_argument('--path',action='append'); selection.add_argument('--suffix',action='append')
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--scratch-dir',type=Path,help='existing game-drive directory for bounded anonymous Zstandard staging')
    p.add_argument('--reference-package',type=Path,required=True)
    a=p.parse_args(argv)
    if a.output.exists(): p.error('output exists; choose a new directory')
    if a.base and not a.keys: p.error('NSP mode requires console keys')
    if a.directory and (a.update or a.keys or a.title): p.error('directory mode cannot use NSP options')
    if not a.reference_package.is_dir(): p.error('reference package directory does not exist')
    decoder=load_decoder()
    options=dict(directory=a.directory) if a.directory else dict(base=a.base,keys=a.keys,update=a.update,title=a.title)
    with ResourceFS(a.library,**options) as resources:
        paths=a.path if a.path else [e.path for e in resources.files() if e.path.endswith(tuple(a.suffix))]
        if not paths: raise ValueError('no selected resource files')
        keys,pairs=collect(resources,paths,a.main,decoder,a.base is not None,scratch=a.scratch_dir)
    profile_keys={line.split('\t')[3] for line in decoder.GAME.table(TABLES[0]).read_text().splitlines()
                  if line and not line.startswith(('#','package\t'))}
    if set(keys)!=profile_keys: raise ValueError('selected sources do not exactly cover the current Profile keys')
    write_package(keys,pairs,a.output,decoder)
    report={'keys':len(keys),'pairs':len(pairs),**compare(a.output,a.reference_package,decoder)}
    (a.output/'comparison.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report))
    if not report['packages_equal'] or not all(report['tables_byte_identical'].values()):
        raise ValueError('export differs from reference; isolated outputs retained for diagnosis')


if __name__=='__main__':
    try: main()
    except (OSError,ValueError) as exc: sys.exit('[RED] package verification failed: '+str(exc))
